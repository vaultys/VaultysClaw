/**
 * Regenerates conformance/status-fixture.json — control-plane-signed status
 * assertions (`cert_status_response`, packages/policy/src/certs/cert-status.ts)
 * for the Go verifier (sdk-go/grant/status.go) to check.
 *
 * The status assertion is what lets an interception point learn a grant was
 * revoked (VC-05): it pairs with the grant in grant-fixture.json by certId and
 * holder, and the Go side must decode `aud`, `seq` and `checkedAt` exactly as
 * TypeScript wrote them — including `aud: null`, which a Go `*string` must read
 * as absent rather than fail on.
 *
 * Same deterministic throwaway key as generate-grant-fixture.ts. Run from the
 * repo root:
 *
 *     pnpm tsx conformance/generate-status-fixture.ts
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { VaultysId, crypto as vaultysCrypto } from "@vaultys/id";
import { signCertStatusResponseCert, verifyCertStatusResponseCert } from "@vaultysclaw/policy";

const TEST_SECRET_SEED = Buffer.alloc(32, 0x2a);
const OUT_PATH = fileURLToPath(new URL("./status-fixture.json", import.meta.url));

async function main() {
  const server = await VaultysId.machineFromEntropy(TEST_SECRET_SEED);
  // Matches grant-fixture.json, so a test can pair the two.
  const certId = "fixture-cert-0001";
  const agentDid = "did:vaultys:test-proxy";
  const checkedAt = Date.UTC(2026, 10, 9, 12, 0, 0);

  const revoked = await signCertStatusResponseCert(server, {
    certId,
    agentDid,
    status: "revoked",
    capabilities: [],
    expiresAt: Date.UTC(2099, 0, 1),
    aud: agentDid,
    seq: checkedAt + 7,
    now: checkedAt,
  });
  const unaddressed = await signCertStatusResponseCert(server, {
    certId,
    agentDid,
    status: "active",
    capabilities: ["internet_access", "api_call"],
    expiresAt: null,
    now: checkedAt,
  });

  for (const token of [revoked, unaddressed]) {
    if (!verifyCertStatusResponseCert(server, token)) {
      throw new Error("a freshly signed status failed its own verification");
    }
  }

  const fixture = {
    $comment: [
      "Generated by conformance/generate-status-fixture.ts — do not hand-edit.",
      "Control-plane-signed cert_status_response assertions, verified by",
      "sdk-go/grant's VerifyStatus (status_fixture_test.go). Signed by the same",
      "fixed throwaway key as grant-fixture.json.",
    ],
    version: 1,
    serverIdBase64: vaultysCrypto.Buffer.from(server.id).toString("base64"),
    serverDid: server.did,
    cases: [
      {
        name: "addressed revoked status with seq",
        token: revoked,
        expected: { certId, agentDid, status: "revoked", checkedAt, aud: agentDid, seq: checkedAt + 7 },
      },
      {
        name: "unaddressed active status, seq defaults to checkedAt",
        token: unaddressed,
        expected: { certId, agentDid, status: "active", checkedAt, aud: null, seq: checkedAt },
      },
    ],
  };

  writeFileSync(OUT_PATH, `${JSON.stringify(fixture, null, 2)}\n`);
  console.log(`wrote ${OUT_PATH}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

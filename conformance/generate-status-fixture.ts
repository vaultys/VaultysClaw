/**
 * Regenerates conformance/status-fixture.json — a `cert_status_response` signed
 * by the TypeScript control plane, for the Go verifier to check
 * (sdk-go/grant/status.go, docs/CERTIFICATE_WEB_OF_TRUST.md §4.1).
 *
 * The other direction — a `cert_status_request` signed by Go and verified here —
 * is conformance/status-request-fixture.json, written by the Go test
 * (`cd sdk-go && go test ./grant -run TestStatusRequestFixture -update`) and
 * checked by packages/policy/__tests__/status-conformance.test.ts.
 *
 * Every optional field carries a non-zero value, so a field the Go struct fails
 * to decode shows up as a wrong answer rather than a coincidentally-correct nil.
 * The status is `revoked`, not `active`, for the same reason: a decode that
 * silently produced the zero value must not read as a healthy certificate.
 *
 * Same fixed throwaway server key as the other fixtures. The requester key is a
 * second fixed throwaway, so the Go side can also check that
 * `vaultysid.MachineFromEntropy` derives the same DID as `VaultysId.machineFromEntropy`.
 *
 * Run from the repo root:
 *
 *     pnpm tsx conformance/generate-status-fixture.ts
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { VaultysId, crypto as vaultysCrypto } from "@vaultys/id";
import { signCertStatusResponseCert, decodeCertUnsafe } from "../packages/policy/src/index";

const TEST_SECRET_SEED = Buffer.alloc(32, 0x2a);
const REQUESTER_SEED = Buffer.alloc(32, 0x17);

const OUT_PATH = fileURLToPath(new URL("./status-fixture.json", import.meta.url));

async function main() {
  const server = await VaultysId.machineFromEntropy(TEST_SECRET_SEED);
  const requester = await VaultysId.machineFromEntropy(REQUESTER_SEED);

  const token = await signCertStatusResponseCert(server, {
    certId: "cert-status-fixture-0001",
    agentDid: requester.did,
    status: "revoked",
    capabilities: ["file_read", "code_execution", "acme:deploy"],
    resourceLimits: { maxRequestsPerHour: 120, allowedDomains: ["api.example.com"] },
    scope: { resourcePattern: "file:///srv/project/*", maxUses: 7 },
    expiresAt: 4102444800000, // 2100-01-01
  });

  const fixture = {
    $comment: [
      "Generated by conformance/generate-status-fixture.ts — do not hand-edit.",
      "A cert_status_response signed by packages/policy's signCertStatusResponseCert,",
      "verified by sdk-go/grant's VerifyStatusResponse (status_test.go).",
      "",
      "requesterSeedHex is the fixed entropy of a second throwaway identity: the Go",
      "test derives it with vaultysid.MachineFromEntropy and must land on",
      "requesterDid, then signs status-request-fixture.json with it for the",
      "TypeScript side to verify.",
      "",
      "Both signing keys are fixed throwaway test keys and grant nothing real.",
    ],
    version: 1,
    serverIdBase64: vaultysCrypto.Buffer.from(server.id).toString("base64"),
    serverDid: server.did,
    requesterSeedHex: REQUESTER_SEED.toString("hex"),
    requesterIdBase64: vaultysCrypto.Buffer.from(requester.id).toString("base64"),
    requesterDid: requester.did,
    token,
    expectedBody: decodeCertUnsafe(token),
  };

  writeFileSync(OUT_PATH, JSON.stringify(fixture, null, 2) + "\n");
  console.log(`wrote ${OUT_PATH}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
